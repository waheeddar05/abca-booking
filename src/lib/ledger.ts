/**
 * Ledger — manually recorded revenue & expenses.
 *
 * ─── Naming note ────────────────────────────────────────────────────
 * This module was specced as "Ad Hoc Revenue / Ad Hoc Expenses". The
 * codebase already uses "ad hoc" for something else entirely — the
 * per-session Match Practice purchase mode (`CorporateBatchMode`, once
 * literally `ADHOC`, renamed to `REGULAR`) — so reusing the phrase for
 * hand-entered accounting would collide on the same dashboard. The
 * money here isn't "ad hoc" either; it's ordinary revenue and ordinary
 * operating costs that simply weren't generated by the booking engine.
 *
 * So the module is the **Ledger**, and its two sides are:
 *   REVENUE → "Manual Revenue"  (vs. system-generated booking/package)
 *   EXPENSE → "Expenses"
 *
 * Everything user-visible uses those words; nothing says "ad hoc".
 * ────────────────────────────────────────────────────────────────────
 *
 * Both sides live in one `LedgerEntry` table discriminated by `kind`,
 * with kind-specific columns nullable at the DB level. This module is
 * the single place that defines what a valid entry of each kind looks
 * like — labels, the expense subcategory catalog, and the Zod schemas
 * shared by the create and update routes.
 */

import { z } from 'zod';

export type LedgerKind = 'REVENUE' | 'EXPENSE';

