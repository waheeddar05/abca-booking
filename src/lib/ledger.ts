// ─── Validation ──────────────────────────────────────────────────────

const dateString = z
  .string()
  .regex(/^\d{4}-\d{2}-\d{2}$/, 'Date must be YYYY-MM-DD')
  .refine((v) => !Number.isNaN(Date.parse(`${v}T00:00:00.000Z`)), 'Invalid date');

const timeString = z
  .string()
  .regex(/^([01]\d|2[0-3]):[0-5]\d$/, 'Time must be HH:MM (24-hour)');

const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max)
    .optional()
    .nullable()
    .transform((v) => (v ? v : null));

/**
 * Shared columns. `recordedById` is intentionally absent — it is always
 * taken from the session server-side, never from the request body.
 *
 * The session block (date + From/To time) is NOT here: it belongs to
 * revenue alone. An expense — a repair bill, a utility payment, a staff
 * payout — has no session behind it, so the expense form has no such
 * field and the schema below rejects nothing because it never accepts
 * one; `toLedgerColumns` nulls those columns for expenses.
 */
const BaseFields = {
  amount: z
    .number({ message: 'Amount is required' })
    .finite('Amount must be a number')
    .positive('Amount must be greater than 0')
    .max(10_000_000, 'Amount looks too large'),
  entryDate: dateString,
  entryTime: timeString,
  paymentMethod: z.enum(LEDGER_PAYMENT_METHODS),
  remarks: optionalText(1000),
  // Who physically handled the money. Validated as a User at this
  // center by the API before it is written.
  collectedById: z
    .string()
    .trim()
    .min(1)
    .max(64)
    .optional()
    .nullable()
    .transform((v) => (v ? v : null)),
};

/**
 * A session range must not end before it starts. Sessions never cross
 * midnight here (centers close well before it), so a plain string
 * compare on HH:MM is the right check.
 */
function checkSessionRange(
  val: { serviceStartTime?: string | null; serviceEndTime?: string | null },
  ctx: z.RefinementCtx,
) {
  if (val.serviceStartTime && val.serviceEndTime && val.serviceEndTime <= val.serviceStartTime) {
    ctx.addIssue({
      code: 'custom',
      path: ['serviceEndTime'],
      message: 'Session "To" time must be after the "From" time',
    });
  }
}

const RevenueEntrySchema = z
  .object({
    kind: z.literal('REVENUE'),
    revenueCategory: z.enum(LEDGER_REVENUE_CATEGORIES),
    customerName: z.string().trim().min(1, 'Customer name is required').max(200),
    // The session this revenue was earned from — all optional.
    serviceDate: dateString.optional().nullable(),
    serviceStartTime: timeString.optional().nullable(),
    serviceEndTime: timeString.optional().nullable(),
    ...BaseFields,
  })
  .superRefine(checkSessionRange);

const ExpenseEntrySchema = z
  .object({
    kind: z.literal('EXPENSE'),
    expenseCategory: z.enum(LEDGER_EXPENSE_CATEGORIES),
    expenseSubcategory: z.string().trim().max(60).optional().nullable(),
    description: z.string().trim().min(1, 'Description is required').max(500),
    paidTo: optionalText(200),
    ...BaseFields,
  })
  .superRefine((val, ctx) => {
    const options = LEDGER_EXPENSE_SUBCATEGORIES[val.expenseCategory] ?? [];
    if (options.length === 0) {
      // MISCELLANEOUS: no subcategory exists, so anything sent is wrong.
      return;
    }
    if (!val.expenseSubcategory) {
      ctx.addIssue({
        code: 'custom',
        path: ['expenseSubcategory'],
        message: 'Subcategory is required for this expense category',
      });
      return;
    }
    if (!options.some((o) => o.value === val.expenseSubcategory)) {
      ctx.addIssue({
        code: 'custom',
        path: ['expenseSubcategory'],
        message: 'Unknown subcategory for this expense category',
      });
    }
  });

/**
 * A whole entry, discriminated by `kind`. Used for both create and
 * update — an edit sends the complete entry, which keeps the per-kind
 * required-field rules enforceable (a partial PATCH could otherwise
 * strip a required column past validation).
 */
export const LedgerEntryInputSchema = z.discriminatedUnion('kind', [
  RevenueEntrySchema,
  ExpenseEntrySchema,
]);

export type LedgerEntryInput = z.infer<typeof LedgerEntryInputSchema>;

/**
 * Normalize validated input into the column set to persist. Columns
 * belonging to the *other* kind are explicitly nulled so switching an
 * entry's kind on edit can never leave stale data behind.
 */
export function toLedgerColumns(input: LedgerEntryInput) {
  const shared = {
    kind: input.kind,
    amount: input.amount,
    entryDate: new Date(`${input.entryDate}T00:00:00.000Z`),
    entryTime: input.entryTime,
    paymentMethod: input.paymentMethod,
    remarks: input.remarks ?? null,
    collectedById: input.collectedById ?? null,
  };

  if (input.kind === 'REVENUE') {
    return {
      ...shared,
      // A "To" time without a "From" describes nothing, so it is
      // dropped rather than stored.
      serviceDate: input.serviceDate ? new Date(`${input.serviceDate}T00:00:00.000Z`) : null,
      serviceStartTime: input.serviceStartTime ?? null,
      serviceEndTime: input.serviceStartTime ? (input.serviceEndTime ?? null) : null,
      revenueCategory: input.revenueCategory,
      customerName: input.customerName,
      expenseCategory: null,
      expenseSubcategory: null,
      description: null,
      paidTo: null,
    };
  }

  return {
    ...shared,
    // Expenses carry no session — nulled explicitly so switching an
    // entry's kind on edit can't leave a stale session behind.
    serviceDate: null,
    serviceStartTime: null,
    serviceEndTime: null,
    revenueCategory: null,
    customerName: null,
    expenseCategory: input.expenseCategory,
    // MISCELLANEOUS has no subcategories — drop anything sent for it.
    expenseSubcategory: categoryHasSubcategories(input.expenseCategory)
      ? (input.expenseSubcategory ?? null)
      : null,
    description: input.description,
    paidTo: input.paidTo ?? null,
  };
}

/** Category label for an entry of either kind, for tables and CSVs. */
export function ledgerCategoryLabel(entry: {
  kind: LedgerKind;
  revenueCategory?: string | null;
  expenseCategory?: string | null;
}): string {
  if (entry.kind === 'REVENUE') {
    const c = entry.revenueCategory as LedgerRevenueCategoryId | null | undefined;
    return c ? (LEDGER_REVENUE_CATEGORY_LABELS[c] ?? c) : '';
  }
  const c = entry.expenseCategory as LedgerExpenseCategoryId | null | undefined;
  return c ? (LEDGER_EXPENSE_CATEGORY_LABELS[c] ?? c) : '';
}
